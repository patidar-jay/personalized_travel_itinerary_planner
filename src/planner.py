"""Planner service.

Orchestrates between the live LLM provider and the deterministic demo engine.
If a live call fails for any reason (no key, bad key, rate limit, parse error),
it transparently falls back to the demo engine and records a status message so
the UI can inform the user. This keeps the app functional end-to-end at all
times.
"""
from __future__ import annotations

from typing import List, Optional, Tuple

from . import demo_engine, prompts
from .llm_provider import LLMProvider, LLMError
from .models import (
    Activity,
    DayPlan,
    Destination,
    Itinerary,
    TripPreferences,
)


def _dest_from_json(data: dict) -> List[Destination]:
    items = data.get("destinations", []) if isinstance(data, dict) else data
    out: List[Destination] = []
    for item in items[:3]:
        try:
            out.append(Destination.from_dict(item))
        except Exception:  # noqa: BLE001 - skip malformed cards
            continue
    return out


def _itinerary_from_json(data: dict, prefs: TripPreferences, destination: str) -> Itinerary:
    itin = Itinerary.from_dict(data)
    # The LLM response does not include preferences; attach the real object.
    itin.preferences = prefs
    if not itin.destination:
        itin.destination = destination
    if not itin.days:
        raise LLMError("Itinerary had no days.")
    return itin


def recommend_destinations(
    prefs: TripPreferences, provider: Optional[LLMProvider]
) -> Tuple[List[Destination], str]:
    """Return (destinations, status_message)."""
    if provider is not None:
        try:
            system, user = prompts.destination_prompt(prefs)
            data = provider.generate_json(system, user)
            dests = _dest_from_json(data)
            if dests:
                return dests, f"Recommended by {provider.provider.title()}."
            raise LLMError("No destinations returned.")
        except LLMError as exc:
            return (
                demo_engine.recommend_destinations(prefs),
                f"Live call failed ({exc}); showing demo recommendations.",
            )
    return demo_engine.recommend_destinations(prefs), "Demo mode recommendations."


def generate_itinerary(
    prefs: TripPreferences, destination: str, provider: Optional[LLMProvider]
) -> Tuple[Itinerary, str]:
    """Return (itinerary, status_message)."""
    if provider is not None:
        try:
            system, user = prompts.itinerary_prompt(prefs, destination)
            data = provider.generate_json(system, user)
            itin = _itinerary_from_json(data, prefs, destination)
            return itin, f"Itinerary generated by {provider.provider.title()}."
        except LLMError as exc:
            return (
                demo_engine.generate_itinerary(prefs, destination),
                f"Live call failed ({exc}); showing demo itinerary.",
            )
    return demo_engine.generate_itinerary(prefs, destination), "Demo mode itinerary."


def swap_day(
    prefs: TripPreferences,
    itinerary: Itinerary,
    day_number: int,
    instruction: str,
    provider: Optional[LLMProvider],
) -> Tuple[DayPlan, str]:
    """Return (revised_day, status_message)."""
    if provider is not None:
        try:
            system, user = prompts.swap_prompt(prefs, itinerary, day_number, instruction)
            data = provider.generate_json(system, user)
            day = DayPlan.from_dict(data)
            if not day.activities:
                raise LLMError("Revised day had no activities.")
            day.day_number = day_number
            return day, f"Day {day_number} revised by {provider.provider.title()}."
        except LLMError as exc:
            return (
                demo_engine.swap_day(prefs, itinerary, day_number, instruction),
                f"Live call failed ({exc}); applied demo revision.",
            )
    return (
        demo_engine.swap_day(prefs, itinerary, day_number, instruction),
        f"Demo mode: Day {day_number} revised.",
    )
