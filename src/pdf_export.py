"""Offline PDF export using fpdf2.

Generates a clean, branded travel itinerary guide including a cover, day-by-day
plan, budget summary, and an emergency contact checklist. Returns raw PDF bytes
so Streamlit's download_button can serve it with no temp files on disk.
"""
from __future__ import annotations

from datetime import datetime
from typing import List

from fpdf import FPDF

from .models import Itinerary, USD_TO_INR

# Wanderlust palette (RGB)
_ORANGE = (255, 107, 53)
_DARK = (43, 33, 24)
_SAND = (255, 243, 230)
_GREY = (110, 110, 110)


def _txt(s: str) -> str:
    """Make text safe for the built-in latin-1 PDF fonts."""
    if s is None:
        return ""
    return str(s).encode("latin-1", "replace").decode("latin-1")


class _ItineraryPDF(FPDF):
    def __init__(self, destination: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.destination = destination
        self.set_auto_page_break(auto=True, margin=18)

    def header(self) -> None:
        if self.page_no() == 1:
            return  # cover page draws its own header
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*_ORANGE)
        self.cell(0, 8, _txt(f"Travel Itinerary - {self.destination}"), ln=True)
        self.set_draw_color(*_ORANGE)
        self.line(10, 20, 200, 20)
        self.ln(4)

    def footer(self) -> None:
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(*_GREY)
        self.cell(0, 10, _txt(f"Page {self.page_no()}  -  Generated by Travel Itinerary Planner"),
                  align="C")


def _emergency_checklist(destination: str) -> List[str]:
    return [
        "Local emergency number (police/ambulance): ____________________",
        "Nearest hospital / clinic: ____________________",
        "Hotel / accommodation address & phone: ____________________",
        "Embassy / consulate contact: ____________________",
        "Travel insurance policy no. & hotline: ____________________",
        "Emergency contact back home: ____________________",
        "Lost card / bank hotline: ____________________",
        "Passport no. & photocopy stored: ____________________",
    ]


def build_itinerary_pdf(itinerary: Itinerary, trip_name: str = "") -> bytes:
    prefs = itinerary.preferences
    pdf = _ItineraryPDF(itinerary.destination)

    # ---------------- Cover page ----------------
    pdf.add_page()
    pdf.set_fill_color(*_ORANGE)
    pdf.rect(0, 0, 210, 60, style="F")
    pdf.set_y(22)
    pdf.set_font("Helvetica", "B", 26)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(0, 12, _txt(trip_name or f"{itinerary.destination} Adventure"), ln=True, align="C")
    pdf.set_font("Helvetica", "", 13)
    pdf.cell(0, 8, _txt(itinerary.destination), ln=True, align="C")

    pdf.ln(24)
    pdf.set_text_color(*_DARK)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 9, _txt("Trip Overview"), ln=True)
    pdf.set_font("Helvetica", "", 11)
    overview = [
        ("Destination", itinerary.destination),
        ("Duration", f"{prefs.duration_days} days"),
        ("Start date", prefs.start_date or "Flexible"),
        ("Vibe", prefs.vibe),
        ("Budget level", prefs.budget_level),
        ("Travel party", prefs.travel_party),
        ("Pace", prefs.pace),
        ("Interests", ", ".join(prefs.interests) or "General"),
    ]
    for label, value in overview:
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(45, 7, _txt(f"{label}:"))
        pdf.set_font("Helvetica", "", 11)
        pdf.cell(0, 7, _txt(value), ln=True)

    # Budget headline
    pdf.ln(4)
    pdf.set_fill_color(*_SAND)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 10, _txt(
        f"Estimated Total: ${itinerary.total_cost_usd:,.0f} USD  |  "
        f"Rs {itinerary.total_cost_inr:,.0f} INR  |  "
        f"{itinerary.total_cost_local:,.0f} {itinerary.local_currency}"
    ), ln=True, fill=True)

    # ---------------- Day-by-day ----------------
    pdf.add_page()
    for day in itinerary.days:
        pdf.set_font("Helvetica", "B", 14)
        pdf.set_text_color(*_ORANGE)
        pdf.cell(0, 9, _txt(day.title or f"Day {day.day_number}"), ln=True)
        pdf.set_font("Helvetica", "I", 10)
        pdf.set_text_color(*_GREY)
        pdf.cell(0, 6, _txt(f"Area / cluster: {day.cluster}"), ln=True)
        pdf.ln(1)

        for a in day.activities:
            pdf.set_text_color(*_DARK)
            pdf.set_font("Helvetica", "B", 11)
            pdf.multi_cell(0, 6, _txt(f"{a.slot}: {a.title}"),
                           new_x="LMARGIN", new_y="NEXT")
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(90, 90, 90)
            meta = f"{a.location}  -  approx ${a.cost_usd:,.0f} USD  -  {a.duration_hrs:g}h"
            pdf.multi_cell(0, 5, _txt(meta), new_x="LMARGIN", new_y="NEXT")
            if a.description:
                pdf.multi_cell(0, 5, _txt(a.description),
                               new_x="LMARGIN", new_y="NEXT")
            pdf.ln(1)

        pdf.set_font("Helvetica", "B", 10)
        pdf.set_text_color(*_DARK)
        pdf.cell(0, 7, _txt(
            f"Day total: ${day.day_cost_usd:,.0f} USD  |  "
            f"Rs {day.day_cost_usd * USD_TO_INR:,.0f} INR"
        ), ln=True)
        pdf.ln(3)
        pdf.set_draw_color(220, 200, 180)
        pdf.line(10, pdf.get_y(), 200, pdf.get_y())
        pdf.ln(4)

    # ---------------- Emergency checklist ----------------
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 15)
    pdf.set_text_color(*_ORANGE)
    pdf.cell(0, 10, _txt("Emergency Contact Checklist"), ln=True)
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(*_DARK)
    pdf.multi_cell(0, 6, _txt(
        "Fill this in before departure and keep an offline copy. "
        "Numbers vary by country; confirm local emergency services on arrival."
    ), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)
    for item in _emergency_checklist(itinerary.destination):
        pdf.set_font("Helvetica", "", 11)
        pdf.multi_cell(0, 8, _txt(f"[ ]  {item}"), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(*_GREY)
    pdf.cell(0, 6, _txt(
        f"Generated {datetime.now().strftime('%Y-%m-%d %H:%M')} - Safe travels!"
    ), ln=True)

    # fpdf2 returns a bytearray; normalize to bytes for Streamlit.
    out = pdf.output()
    return bytes(out)
